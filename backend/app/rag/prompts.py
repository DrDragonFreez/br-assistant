"""Промпты для всех узлов графа.

Промпт — основной инструмент снижения риска ошибочных ответов. Здесь
реализованы три защитных механизма:

1. **Жёсткое ограничение источника.** Модели прямо запрещено использовать
   что-либо, кроме переданных фрагментов инструкции.
2. **Обязательная ссылка.** Каждое утверждение сопровождается номером пункта
   в формате ``[п. X.Y]``; без ссылки утверждение не допускается.
3. **Явный отказ.** Если контекста недостаточно, модель обязана вернуть
   фиксированную фразу, а не правдоподобную догадку.
"""

from __future__ import annotations

from typing import Any

NO_ANSWER_MARKER = "НЕТ_В_БАЗЕ_ЗНАНИЙ"
NO_ANSWER_MESSAGE = (
    "В базе знаний нет информации по этому вопросу. "
    "Рекомендую обратиться в Центр документационного обеспечения — "
    "возможно, требование содержится в документе, который ещё не загружен в систему."
)

# ═══════════════════════════ ГЕНЕРАЦИЯ ОТВЕТА ═══════════════════════════
SYSTEM_PROMPT = """Ты — помощник сотрудника Банка России по внутренним регламентам и документообороту.

ТВОЯ ЗАДАЧА: объяснять требования инструкций простым языком, опираясь ИСКЛЮЧИТЕЛЬНО на приведённые фрагменты.

АБСОЛЮТНЫЕ ПРАВИЛА:
1. Используй ТОЛЬКО информацию из блока «ФРАГМЕНТЫ ИНСТРУКЦИИ». Твои общие знания о документообороте в других организациях здесь неприменимы и могут быть ошибочны.
2. После каждого утверждения ставь ссылку на источник в квадратных скобках: [п. 3.4] или [Приложение 2] — ровно так, как номер указан во фрагменте.
3. Если во фрагментах нет ответа на вопрос — верни ровно одну строку: {no_answer_marker}
   Не придумывай требования, не достраивай логику, не предполагай «обычно так принято».
4. Если фрагменты отвечают на вопрос лишь частично — изложи то, что подтверждено ссылками, и прямо укажи, какая часть вопроса осталась без ответа в базе знаний.
5. Не ссылайся на пункты, которых нет во фрагментах. Выдуманная ссылка хуже отсутствия ответа.

СТИЛЬ ОТВЕТА:
- Переводи канцелярит в понятные формулировки, но сохраняй точность требования: сроки, количество экземпляров, состав согласующих подразделений передавай дословно.
- Отвечай по существу, без вводных оборотов и без пересказа вопроса.
- Для последовательности действий используй нумерованный список.
- Сроки и количественные требования выделяй **полужирным**.
- Объём: 3–8 предложений, если вопрос не требует развёрнутой процедуры.

ЧЕГО НЕ ДЕЛАТЬ:
- Не давай юридических оценок и не толкуй нормы расширительно.
- Не упоминай, что работаешь с «фрагментами», «контекстом» или «базой знаний» — для сотрудника это просто текст инструкции.
- Не повторяй одну и ту же ссылку в каждом предложении подряд, если утверждения относятся к одному пункту."""


USER_PROMPT_TEMPLATE = """ФРАГМЕНТЫ ИНСТРУКЦИИ:
{context}

{history_block}ВОПРОС СОТРУДНИКА: {question}

Ответь по правилам, со ссылками на пункты."""


def format_context(chunks: list[Any], *, max_chars: int = 7000) -> str:
    """Собирает контекст из найденных фрагментов.

    Каждый фрагмент снабжается явным адресом (документ, пункт, страница),
    чтобы модель могла корректно сослаться на него в ответе.

    Args:
        chunks: Найденные фрагменты (:class:`RetrievedChunk`).
        max_chars: Ограничение по длине контекста.

    Returns:
        Отформатированный блок контекста.
    """
    if not chunks:
        return "(фрагменты не найдены)"

    parts: list[str] = []
    total = 0

    for position, chunk in enumerate(chunks, start=1):
        address_items = [chunk.document_title or chunk.document_code]
        if chunk.annex_number:
            address_items.append(f"Приложение {chunk.annex_number}")
        clauses = (getattr(chunk, "extra", None) or {}).get("clauses") or []
        if len(clauses) > 1:
            address_items.append("п. " + ", ".join(str(item) for item in clauses))
        elif chunk.clause_number:
            address_items.append(f"п. {chunk.clause_number}")
        if chunk.section_title and not chunk.annex_number:
            address_items.append(chunk.section_title)
        if chunk.page_number:
            address_items.append(f"с. {chunk.page_number}")

        header = f"--- Фрагмент {position} | {' | '.join(filter(None, address_items))} ---"
        body = chunk.content.strip()
        block = f"{header}\n{body}"

        if total + len(block) > max_chars:
            break
        parts.append(block)
        total += len(block)

    return "\n\n".join(parts)


def format_history(messages: list[dict[str, str]], *, max_messages: int = 6) -> str:
    """Форматирует историю диалога для учёта контекста.

    Args:
        messages: Сообщения в формате ``{"role": ..., "content": ...}``.
        max_messages: Сколько последних сообщений включить.

    Returns:
        Блок истории либо пустая строка.
    """
    if not messages:
        return ""

    recent = messages[-max_messages:]
    lines = [
        f"{'Сотрудник' if item['role'] == 'user' else 'Помощник'}: {item['content'][:400]}"
        for item in recent
    ]
    return "ПРЕДЫДУЩИЕ РЕПЛИКИ ДИАЛОГА:\n" + "\n".join(lines) + "\n\n"


def build_answer_prompt(
    question: str,
    chunks: list[Any],
    history: list[dict[str, str]] | None = None,
) -> tuple[str, str]:
    """Собирает системный и пользовательский промпты для генерации ответа.

    Args:
        question: Вопрос сотрудника.
        chunks: Найденные фрагменты инструкции.
        history: История диалога.

    Returns:
        Кортеж ``(системный промпт, пользовательский промпт)``.
    """
    system = SYSTEM_PROMPT.format(no_answer_marker=NO_ANSWER_MARKER)
    user = USER_PROMPT_TEMPLATE.format(
        context=format_context(chunks),
        history_block=format_history(history or []),
        question=question.strip(),
    )
    return system, user


