SLOT_FILLING_SYSTEM_PROMPT = """Ты помогаешь сотруднику заполнить бланк документа.

Извлеки из реплики значения полей и верни ТОЛЬКО JSON:
{
  "extracted": {"<имя поля>": "<значение>"},
  "still_missing": ["<имя обязательного поля>"],
  "next_question": "<вопрос про одно следующее поле или пустая строка>"
}

ПРАВИЛА:
- Извлекай только то, что сотрудник действительно сообщил. Не достраивай значения по смыслу.
- Спрашивай по одному полю за раз, начиная с обязательных.
- Если сотрудник отказался заполнять необязательное поле — не спрашивай повторно.
- Формулировки для вставки в документ делай официальными, но не меняй смысл сказанного."""


SLOT_FILLING_USER_TEMPLATE = """ПОЛЯ ШАБЛОНА «{template_name}»:
{fields_description}

УЖЕ ЗАПОЛНЕНО: {filled}

РЕПЛИКА СОТРУДНИКА: {message}

JSON:"""


def build_slot_filling_prompt(
    template_name: str,
    fields: list[dict[str, Any]],
    filled: dict[str, Any],
    message: str,
) -> tuple[str, str]:
    """Собирает промпты для пошагового заполнения шаблона.

    Args:
        template_name: Название шаблона.
        fields: Схема полей шаблона.
        filled: Уже собранные значения.
        message: Последняя реплика сотрудника.

    Returns:
        Кортеж ``(системный промпт, пользовательский промпт)``.
    """
    description = "\n".join(
        f"- {field['name']}: {field.get('label', '')}"
        f"{' (обязательное)' if field.get('required') else ''}"
        for field in fields
    )
    return SLOT_FILLING_SYSTEM_PROMPT, SLOT_FILLING_USER_TEMPLATE.format(
        template_name=template_name,
        fields_description=description,
        filled=", ".join(f"{k}={v}" for k, v in filled.items()) if filled else "ничего",
        message=message.strip(),
    )


