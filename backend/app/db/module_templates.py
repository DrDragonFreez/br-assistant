# Сроки рассмотрения проекта подразделением, [п. 10.3] инструкции.
TERM_ORDER_DAYS = 10
TERM_DIRECTION_DAYS = 3

# Подразделения, которые Матрица обязательного визирования называет
# для каждой строки. Порядок визирования — по [п. 4.2] Методических
# рекомендаций: подразделение-исполнитель, затем профильные
# подразделения, лингвистическая экспертиза и Департамент ДОУ последним.
LEGAL = "Юридическое подразделение"
DOU = "Департамент ДОУ"
HR = "Кадровое подразделение"
INFOSEC = "Департамент информационной безопасности"
IT = "Департамент информационных технологий"


def _route(*departments: str, term_days: int) -> list[dict[str, Any]]:
    """Собирает маршрут визирования из перечня подразделений.

    Args:
        *departments: Подразделения в порядке прохождения.
        term_days: Срок рассмотрения каждым подразделением.

    Returns:
        Список шагов маршрута для поля ``required_approvals``.
    """
    return [
        {"department": department, "term_days": term_days, "order": position}
        for position, department in enumerate(departments, start=1)
    ]


def _field(
    name: str,
    label: str,
    question: str,
    *,
    type: str = "string",
    required: bool = True,
    options: list[str] | None = None,
) -> dict[str, Any]:
    """Описывает поле бланка.

    Текст вопроса взят из примечаний к модулю: организаторы уже
    сформулировали, что именно нужно указать в каждом пропуске, и
    придумывать свои формулировки незачем.

    Args:
        name: Имя поля; совпадает с именем в шаблоне DOCX.
        label: Подпись поля в интерфейсе.
        question: Вопрос, который задаёт помощник при заполнении.
        type: Тип поля: string, text, date, number, list.
        required: Обязательно ли поле.
        options: Допустимые значения для выбора.

    Returns:
        Запись схемы полей шаблона.
    """
    payload: dict[str, Any] = {
        "name": name,
        "label": label,
        "type": type,
        "required": required,
        "question": question,
    }
    if options:
        payload["options"] = options
    return payload


