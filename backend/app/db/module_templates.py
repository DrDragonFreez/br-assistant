"""Каталог модульных документов из материалов кейса.

Организаторы передали семь модулей — приказы и распоряжения с постоянными
формулировками, пропусками для заполнения и нумерованными примечаниями.
Этот файл описывает каждый из них в одном месте и используется дважды:

* ``app.db.seed`` регистрирует модули в реестре шаблонов — по ним помощник
  подбирает бланк и задаёт вопросы при заполнении;
* ``scripts/build_templates.py`` по карте ``layout`` превращает исходный
  файл модуля в шаблон docxtpl: подчёркивания становятся полями, а
  примечания, гриф утверждения и пометка «МОДУЛЬНЫЙ ДОКУМЕНТ» удаляются,
  как требует §3.3 Методических рекомендаций.

Единый источник правды выбран сознательно: имена полей встречаются и в
схеме вопросов, и в шаблоне DOCX, и расхождение между ними проявилось бы
только на защите — пустым реквизитом в готовом документе.

Состав визирующих подразделений взят из Матрицы обязательного
визирования, сроки рассмотрения — из [п. 10.3] инструкции: приказ по
основной деятельности — 10 рабочих дней, распоряжение — 3 рабочих дня.
"""

