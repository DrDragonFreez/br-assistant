@dataclass(frozen=True, slots=True)
class ModuleTemplate:
    """Модульный документ: описание для реестра и карта для конвертера.

    Attributes:
        code: Код шаблона в реестре.
        source: Имя исходного файла модуля от организаторов.
        name: Название документа.
        doc_kind: Вид документа: ``order`` либо ``direction``.
        description: Назначение модуля — показывается при подборе бланка.
        keywords: Слова, по которым модуль находится по обращению.
        related_clauses: Пункты инструкции с требованиями к документу.
        required_approvals: Маршрут обязательного визирования.
        fields: Схема полей для заполнения.
        layout: Карта правок исходного DOCX; нужна только конвертеру.
        access_level: Гриф доступа к бланку.
    """

    code: str
    source: str
    name: str
    doc_kind: str
    description: str
    keywords: list[str]
    related_clauses: list[str]
    required_approvals: list[dict[str, Any]]
    fields: list[dict[str, Any]]
    layout: dict[str, Any] = field(default_factory=dict)
    access_level: AccessLevel = AccessLevel.INTERNAL

    @property
    def filename(self) -> str:
        """Имя файла готового шаблона docxtpl."""
        return f"{self.code}.docx"

    def to_db_payload(self, templates_dir: str = "/app/data/templates") -> dict[str, Any]:
        """Готовит запись для таблицы ``document_templates``.

        Args:
            templates_dir: Каталог шаблонов внутри контейнера.

        Returns:
            Поля модели :class:`app.db.models.DocumentTemplate`.
        """
        return {
            "code": self.code,
            "name": self.name,
            "description": self.description,
            "doc_kind": self.doc_kind,
            "file_path": f"{templates_dir}/{self.filename}",
            "keywords": list(self.keywords),
            "fields_schema": [dict(item) for item in self.fields],
            "required_approvals": [dict(item) for item in self.required_approvals],
            "related_clauses": list(self.related_clauses),
            "access_level": self.access_level,
            "is_active": True,
            "version": 1,
        }


